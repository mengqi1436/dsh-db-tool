import { chromium } from 'playwright';
const base = process.argv[2]; const tag = process.argv[3];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 500, height: 774 }, colorScheme: 'light' });
await page.goto(base + '/?bg=light');
await page.waitForSelector('.dbt-tabs');
await page.getByRole('tab', { name: '数据浏览' }).click();
const treehead = page.locator('button.dbt-browse-treehead').first();
if ((await treehead.getAttribute('aria-expanded')) === 'false') await treehead.click();
await page.waitForSelector('.dbt-treerow');
await page.locator('.dbt-treerow', { hasText: 'main' }).first().click();
await page.waitForSelector('.dbt-treerow:has-text("orders")');
await page.locator('.dbt-treerow', { hasText: 'orders' }).first().click();
await page.getByRole('tab', { name: '数据预览' }).click();
await page.waitForSelector('.dbt-browse-footer');
await page.getByRole('button', { name: '筛选', exact: true }).click();
await page.waitForSelector('.dbt-filter-pane');
const rowsLoc = page.locator('.dbt-filter-pane .dbt-filter-row:has(select)');
await rowsLoc.nth(0).locator('select').nth(0).selectOption('buyer');
await rowsLoc.nth(0).locator('input[type=text]').first().fill('ali');
await page.getByRole('button', { name: '应用筛选' }).click();
await page.waitForSelector('.dbt-browse-footer:has-text("匹配")', { timeout: 20000 });
await page.waitForTimeout(300);
const paneAfterApply = await page.locator('.dbt-filter-pane').count();
const tableBox = await page.locator('.dbt-table').boundingBox();
const filterBtnText = await page.locator('.dbt-browse-footer button', { hasText: '筛选' }).innerText();
console.log(`[${tag}] paneAfterApply=${paneAfterApply} tableTop=${Math.round(tableBox.y)} filterBtn="${filterBtnText}"`);
await browser.close();
